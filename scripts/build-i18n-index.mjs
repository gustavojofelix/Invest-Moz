// Generates src/app/core/i18n/translation-files.ts: one lazy import per UI
// translation file in src/assets/i18n (the global file per locale, and
// <scope>/<locale>.json for each feature scope). Re-run after adding a scope.
// Usage: node scripts/build-i18n-index.mjs
import { readdirSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const I18N = 'src/assets/i18n';
const LOCALES = ['pt', 'en', 'fr', 'zh', 'ar', 'hi', 'sw', 'af'];

const scopes = readdirSync(I18N)
  .filter((e) => statSync(join(I18N, e)).isDirectory())
  .sort();

const lines = [];
for (const l of LOCALES) lines.push(`  ${l}: () => import('../../../assets/i18n/${l}.json'),`);
for (const s of scopes) {
  for (const l of LOCALES) {
    lines.push(`  '${s}/${l}': () => import('../../../assets/i18n/${s}/${l}.json'),`);
  }
}

writeFileSync(
  'src/app/core/i18n/translation-files.ts',
  `// Generated by scripts/build-i18n-index.mjs. Do not edit.
import type { Translation } from '@jsverse/transloco';

type JsonModule = Promise<{ default: Translation }>;

export const TRANSLATION_SCOPES = [
${scopes.map((s) => `  '${s}',`).join('\n')}
] as const;
export type TranslationScope = (typeof TRANSLATION_SCOPES)[number];

/** "<lang>" for the global file, "<scope>/<lang>" for feature scopes. */
export const TRANSLATION_FILES: Record<string, () => JsonModule> = {
${lines.join('\n')}
};
`,
);
console.log(
  `✓ ${scopes.length} scopes × ${LOCALES.length} locales written to translation-files.ts`,
);
