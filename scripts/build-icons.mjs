// Generates src/app/shared/ui/icons.data.ts with only the Lucide icons the app
// uses (Lucide is ISC-licensed, https://lucide.dev). The @lucide/angular build
// cannot be tree-shaken per icon, so we keep our own small set instead.
//
// Usage: node scripts/build-icons.mjs   (re-run after adding an icon to NAMES)
import { readFileSync, writeFileSync } from 'node:fs';

const NAMES = [
  'ArrowLeft',
  'ArrowRight',
  'ArrowUp',
  'Check',
  'ChevronDown',
  'CircleAlert',
  'Copy',
  'FileText',
  'Flag',
  'FolderOpen',
  'Info',
  'KeyRound',
  'LockKeyhole',
  'LogIn',
  'LogOut',
  'Mail',
  'Menu',
  'MessageSquareText',
  'Moon',
  'Phone',
  'Printer',
  'RotateCcw',
  'Search',
  'Send',
  'Square',
  'Sun',
  'TriangleAlert',
  'X',
];

const src = readFileSync('node_modules/@lucide/angular/fesm2022/lucide-angular.mjs', 'utf8');
const icons = {};
for (const name of NAMES) {
  const re = new RegExp(
    `class Lucide${name} extends LucideIconBase \\{\\s*static icon = (\\{[\\s\\S]*?\\n\\t\\});`,
  );
  const m = re.exec(src);
  if (!m) throw new Error(`Icon not found: ${name}`);
  const icon = Function(`return (${m[1]});`)();
  icons[icon.name] = icon.node.map(([tag, attrs]) => {
    const rest = { ...attrs };
    delete rest.key;
    return [tag, rest];
  });
}

writeFileSync(
  'src/app/shared/ui/icons.data.ts',
  `// Generated by scripts/build-icons.mjs from Lucide (ISC License, https://lucide.dev). Do not edit.
export type IconNode = [string, Record<string, string | number>][];

export const ICONS: Record<string, IconNode> = ${JSON.stringify(icons, null, 2)};

export type IconName = keyof typeof ICONS;
`,
);
console.log(`✓ ${Object.keys(icons).length} icons written to src/app/shared/ui/icons.data.ts`);
